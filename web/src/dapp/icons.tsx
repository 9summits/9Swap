export type IconProps = {
  name: IconName;
  size?: number;
  stroke?: number;
  style?: React.CSSProperties;
};

export function Icon({ name, size = 18, stroke = 2, style = {} }: IconProps) {
  const p = ICON_PATHS[name];
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={stroke}
      strokeLinecap="round"
      strokeLinejoin="round"
      style={{
        flex: "none",
        ...(name === "spinner" ? { animation: "spin9 0.8s linear infinite" } : {}),
        ...style,
      }}
    >
      {p}
    </svg>
  );
}

// Keyframe used by the spinner icon. Mount this once near the app root so the
// `spin9` animation referenced above resolves.
export function IconKeyframes() {
  return <style>{`@keyframes spin9{to{transform:rotate(360deg)}}`}</style>;
}
